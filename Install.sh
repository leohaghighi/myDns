#!/usr/bin/env bash
# Xbox Smart DNS + Telegram manager bot - one-line installer (Ubuntu/Debian).
#
#   bash <(curl -fsSL https://raw.githubusercontent.com/YOUR_USER/YOUR_REPO/main/install.sh)
#
# Optional: BOT_TOKEN=123:abc bash <(curl -fsSL ...)   (skips the token question)
# Safe to re-run: it updates the scripts and restarts the bot without losing users.
set -euo pipefail

[ "$(id -u)" -eq 0 ] || { echo "Run as root first:  sudo -i   (then paste the command again)"; exit 1; }
command -v apt-get >/dev/null || { echo "This installer supports Ubuntu/Debian only."; exit 1; }
export DEBIAN_FRONTEND=noninteractive

need=""
command -v curl >/dev/null || need="$need curl"
command -v python3 >/dev/null || need="$need python3"
if [ -n "$need" ]; then apt-get update -qq; apt-get install -y -qq $need; fi

# ---- 1. Telegram bot token (checked before anything is changed) ----
BOT_TOKEN="${BOT_TOKEN:-}"
if [ -z "$BOT_TOKEN" ]; then
  echo "1) In Telegram open @BotFather, send /newbot, and copy the token it gives you."
  read -r -p "2) Paste the bot token here: " BOT_TOKEN </dev/tty
fi
BOT_TOKEN=$(printf '%s' "$BOT_TOKEN" | tr -d '[:space:]')
[[ $BOT_TOKEN =~ ^[0-9]+:[A-Za-z0-9_-]{30,}$ ]] || { echo "That does not look like a bot token."; exit 1; }
ME=$(curl -fsS --max-time 20 "https://api.telegram.org/bot$BOT_TOKEN/getMe") \
  || { echo "Telegram rejected the token (or api.telegram.org is unreachable from this server)."; exit 1; }
BOT_USER=$(printf '%s' "$ME" | python3 -c 'import sys,json; print(json.load(sys.stdin)["result"]["username"])')

# ---- 2. Unpack the components ----
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT

cat > "$T/smartdns.sh" <<'SMARTDNS_SH_PAYLOAD_EOF'
#!/usr/bin/env bash
# smartdns - personal Xbox Smart DNS (dnsmasq + sniproxy) for a VPS that already runs Amnezia VPN.
#
#   sudo bash smartdns.sh install [HOME_IP ...]      one-time setup (IPs optional)
#   sudo smartdns ip <IP> [more IPs] | none          set the allowed IP list (replaces the old list)
#   sudo smartdns add <domain>                       route one more domain through the VPS
#   sudo smartdns remove <domain>
#   smartdns list | status | logs
#   sudo smartdns uninstall                          remove everything
#
# Safety: it never touches Docker/Amnezia. If port 53, 80 or 443 is already in use, it stops
# before changing anything. Only your home IP is allowed to use the service.

set -euo pipefail

CONF_DIR=/etc/smartdns
DOMAINS_FILE="$CONF_DIR/domains.txt"
STATE_FILE="$CONF_DIR/state.env"
SNI_CONF="$CONF_DIR/sniproxy.conf"
DNSMASQ_CONF=/etc/dnsmasq.d/smartdns.conf
FW_SCRIPT=/usr/local/sbin/smartdns-firewall.sh
BIN=/usr/local/bin/smartdns
UNIT_SNI=/etc/systemd/system/smartdns-sniproxy.service
UNIT_FW=/etc/systemd/system/smartdns-firewall.service
CHAIN=SMARTDNS

say() { printf '%s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
need_root() { [ "$(id -u)" -eq 0 ] || die "Run this with sudo (or as root)."; }

valid_ip() {
  local ip=$1 o
  local -a parts
  [[ $ip =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || return 1
  IFS=. read -ra parts <<<"$ip"
  for o in "${parts[@]}"; do (( 10#$o <= 255 )) || return 1; done
  return 0
}

valid_domain() { [[ $1 =~ ^[a-z0-9]([a-z0-9.-]*[a-z0-9])?\.[a-z]{2,}$ ]]; }

# true if something (other than loopback-only services) listens on proto(t|u) port
port_busy() {
  local out
  out=$(ss -H -ln"$1" "sport = :$2" 2>/dev/null | awk '{print $4}' | grep -Ev '^(127\.|\[::1\])' || true)
  [ -n "$out" ]
}

pkg_installed() { dpkg-query -W -f='${Status}' "$1" 2>/dev/null | grep -q 'install ok installed'; }

detect_ips() {
  LOCAL_IP=$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<NF;i++) if($i=="src"){print $(i+1); exit}}')
  [ -n "${LOCAL_IP:-}" ] || die "Could not detect this server's IP address."
  PUBLIC_IP=$(curl -4 -fsS --max-time 10 https://api.ipify.org 2>/dev/null \
    || curl -4 -fsS --max-time 10 https://ifconfig.me 2>/dev/null || true)
  valid_ip "${PUBLIC_IP:-x}" || PUBLIC_IP=$LOCAL_IP
}

render_configs() {
  # shellcheck disable=SC1090
  . "$STATE_FILE"
  local d re
  local -a DOMS
  mapfile -t DOMS < <(grep -Ev '^[[:space:]]*(#|$)' "$DOMAINS_FILE" || true)

  {
    echo "# Generated by smartdns. Use 'smartdns add/remove' instead of editing."
    echo "listen-address=$LOCAL_IP"
    echo "bind-dynamic"
    echo "no-resolv"
    echo "no-hosts"
    echo "cache-size=1000"
    echo "log-queries"
    echo "server=1.1.1.1"
    echo "server=9.9.9.9"
    for d in "${DOMS[@]}"; do echo "address=/$d/$PUBLIC_IP"; done
  } > "$DNSMASQ_CONF"

  {
    cat <<EOF
user daemon
pidfile /run/smartdns-sniproxy.pid

error_log {
    syslog daemon
    priority notice
}

# IMPORTANT: sniproxy must use real DNS servers, never this server's own dnsmasq (that would loop).
resolver {
    nameserver 1.1.1.1
    nameserver 9.9.9.9
    mode ipv4_only
}

listener $LOCAL_IP:80 {
    proto http
    table smart_http
}

listener $LOCAL_IP:443 {
    proto tls
    table smart_tls
}

table smart_http {
EOF
    for d in "${DOMS[@]}"; do re=${d//./\\.}; echo "    (^|\\.)$re\$ *:80"; done
    echo "}"
    echo
    echo "table smart_tls {"
    for d in "${DOMS[@]}"; do re=${d//./\\.}; echo "    (^|\\.)$re\$ *:443"; done
    echo "}"
  } > "$SNI_CONF"
}

restart_services() {
  systemctl restart dnsmasq
  systemctl restart smartdns-sniproxy
}

do_uninstall() {
  set +e
  systemctl disable --now smartdns-bot 2>/dev/null
  rm -f /etc/systemd/system/smartdns-bot.service
  rm -rf /opt/smartdns-bot
  systemctl disable --now smartdns-sniproxy 2>/dev/null
  systemctl disable --now smartdns-firewall 2>/dev/null
  systemctl disable --now dnsmasq 2>/dev/null
  if command -v iptables >/dev/null 2>&1; then
    # shellcheck disable=SC2086
    iptables -S INPUT 2>/dev/null | grep -- "-j $CHAIN" | sed 's/^-A/-D/' | while read -r r; do iptables $r; done
    iptables -F "$CHAIN" 2>/dev/null
    iptables -X "$CHAIN" 2>/dev/null
  fi
  rm -f "$UNIT_SNI" "$UNIT_FW" "$DNSMASQ_CONF" "$FW_SCRIPT"
  rm -rf "$CONF_DIR"
  systemctl daemon-reload 2>/dev/null
  DEBIAN_FRONTEND=noninteractive apt-get purge -y -qq sniproxy dnsmasq >/dev/null 2>&1
  [ "${MADE_PRC:-0}" = 1 ] && rm -f /usr/sbin/policy-rc.d
  rm -f "$BIN"
}

cmd_install() {
  need_root
  [ ! -f "$STATE_FILE" ] || die "Already installed. Use 'sudo smartdns ip <new IP>' or 'sudo smartdns uninstall'."
  [ -f "${BASH_SOURCE[0]}" ] || die "Save this script to a file first, then run it (do not pipe it into bash)."
  command -v apt-get >/dev/null || die "This script supports Ubuntu/Debian only."
  local ip
  for ip in "$@"; do valid_ip "$ip" || die "'$ip' is not a valid IPv4 address."; done

  # ---- Safety checks: nothing has been changed yet ----
  if pkg_installed sniproxy || pkg_installed dnsmasq; then
    die "sniproxy or dnsmasq is already installed on this server. Not touching it. Nothing was changed."
  fi
  local spec busy=0
  for spec in "u 53" "t 53" "t 80" "t 443"; do
    if port_busy "${spec% *}" "${spec#* }"; then
      say "Port ${spec#* } ($([ "${spec% *}" = t ] && echo TCP || echo UDP)) is already used by another program on this server."
      busy=1
    fi
  done
  if [ "$busy" = 1 ]; then
    say "Most likely Amnezia (e.g. Xray/OpenVPN on 443). To see who: sudo ss -lntup | grep -E ':(53|80|443)\\b'"
    say "Nothing was changed. Fix: change that Amnezia protocol's port in the Amnezia app, or use a server/IP where these ports are free."
    exit 1
  fi

  # ---- Install (with automatic rollback if anything fails) ----
  CHANGED=1
  DONE=0
  trap 'if [ "${DONE:-0}" != 1 ]; then echo "Install failed - rolling back..." >&2; do_uninstall; fi' EXIT

  local prc=/usr/sbin/policy-rc.d
  MADE_PRC=0
  if [ ! -e "$prc" ]; then printf '#!/bin/sh\nexit 101\n' > "$prc"; chmod +x "$prc"; MADE_PRC=1; fi
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y -qq sniproxy dnsmasq iptables curl
  [ "$MADE_PRC" = 1 ] && rm -f "$prc"

  systemctl disable --now sniproxy >/dev/null 2>&1 || true
  if [ -f /etc/default/dnsmasq ] && ! grep -q '^IGNORE_RESOLVCONF=yes' /etc/default/dnsmasq; then
    echo 'IGNORE_RESOLVCONF=yes' >> /etc/default/dnsmasq
  fi

  detect_ips
  mkdir -p "$CONF_DIR"
  cat > "$DOMAINS_FILE" <<'EOF'
# One domain per line (subdomains are included automatically).
xboxlive.com
xbox.com
xboxservices.com
gamepass.com
live.com
microsoft.com
microsoftonline.com
msauth.net
msftauth.net
msftconnecttest.com
EOF
  cat > "$STATE_FILE" <<EOF
LOCAL_IP=$LOCAL_IP
PUBLIC_IP=$PUBLIC_IP
HOME_IPS="$*"
EOF
  chmod 600 "$STATE_FILE"
  cp -f "${BASH_SOURCE[0]}" "$BIN" && chmod +x "$BIN"

  # Firewall: only whitelisted home IPs may reach DNS/HTTP/HTTPS on this server's address.
  # Only these three ports are touched; Docker/Amnezia rules are left alone.
  cat > "$FW_SCRIPT" <<'EOF'
#!/bin/sh
. /etc/smartdns/state.env
CHAIN=SMARTDNS
iptables -N $CHAIN 2>/dev/null || true
iptables -F $CHAIN
for ip in $HOME_IPS; do iptables -A $CHAIN -s "$ip" -j RETURN; done
iptables -A $CHAIN -j DROP
for spec in "udp 53" "tcp 53" "tcp 80" "tcp 443"; do
  set -- $spec
  iptables -C INPUT -d "$LOCAL_IP" -p "$1" --dport "$2" -j $CHAIN 2>/dev/null || \
    iptables -I INPUT 1 -d "$LOCAL_IP" -p "$1" --dport "$2" -j $CHAIN
done
EOF
  chmod +x "$FW_SCRIPT"

  local sniproxy_bin
  sniproxy_bin=$(command -v sniproxy) || die "sniproxy binary not found."

  cat > "$UNIT_FW" <<EOF
[Unit]
Description=Smart DNS firewall (only whitelisted home IPs)
After=network-online.target
Wants=network-online.target
Before=dnsmasq.service smartdns-sniproxy.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=$FW_SCRIPT

[Install]
WantedBy=multi-user.target
EOF

  cat > "$UNIT_SNI" <<EOF
[Unit]
Description=Smart DNS SNI proxy (personal)
After=network-online.target smartdns-firewall.service
Wants=network-online.target smartdns-firewall.service

[Service]
Type=forking
PIDFile=/run/smartdns-sniproxy.pid
ExecStart=$sniproxy_bin -c $SNI_CONF
Restart=on-failure

[Install]
WantedBy=multi-user.target
EOF

  render_configs
  dnsmasq --test -C "$DNSMASQ_CONF" >/dev/null 2>&1 || die "dnsmasq config check failed."

  systemctl daemon-reload
  systemctl enable --now smartdns-firewall
  systemctl enable dnsmasq >/dev/null 2>&1
  systemctl enable smartdns-sniproxy >/dev/null 2>&1
  restart_services
  sleep 2
  systemctl is-active --quiet dnsmasq || die "dnsmasq did not start (see: journalctl -u dnsmasq -n 30)."
  systemctl is-active --quiet smartdns-sniproxy || die "sniproxy did not start (see: journalctl -u smartdns-sniproxy -n 30)."

  DONE=1
  trap - EXIT
  say
  say "Done. Smart DNS is running."
  say "  On your Xbox set DNS to (manual):  $PUBLIC_IP"
  say "  Secondary DNS: same IP, or 1.1.1.1"
  say "  Allowed home IP(s): ${*:-none yet}"
  say "To change the allowed IP later:  sudo smartdns ip <NEW_IP>"
  say "Also make sure your VPS provider's own firewall (if any) allows ports 53 (UDP+TCP), 80 and 443."
}

cmd_ip() {
  need_root
  [ -f "$STATE_FILE" ] || die "Not installed."
  [ $# -ge 1 ] || die "Usage: sudo smartdns ip <YOUR_HOME_IP> [more IPs]   (or: none)"
  local ip
  if [ "$1" = none ]; then
    set --
  else
    for ip in "$@"; do valid_ip "$ip" || die "'$ip' is not a valid IPv4 address."; done
  fi
  sed -i "s/^HOME_IPS=.*/HOME_IPS=\"$*\"/" "$STATE_FILE"
  "$FW_SCRIPT"
  say "Allowed IP(s) now: ${*:-none}"
}

cmd_add() {
  need_root
  [ -f "$STATE_FILE" ] || die "Not installed."
  local d=${1:-}
  d=${d,,}
  valid_domain "$d" || die "Usage: sudo smartdns add example.com"
  grep -qx "$d" "$DOMAINS_FILE" && { say "$d is already in the list."; return 0; }
  echo "$d" >> "$DOMAINS_FILE"
  render_configs
  restart_services
  say "Added $d (subdomains included)."
}

cmd_remove() {
  need_root
  [ -f "$STATE_FILE" ] || die "Not installed."
  local d=${1:-}
  d=${d,,}
  valid_domain "$d" || die "Usage: sudo smartdns remove example.com"
  grep -vx "$d" "$DOMAINS_FILE" > "$DOMAINS_FILE.new" || true
  mv "$DOMAINS_FILE.new" "$DOMAINS_FILE"
  render_configs
  restart_services
  say "Removed $d."
}

cmd_list() {
  [ -f "$DOMAINS_FILE" ] || die "Not installed."
  grep -Ev '^[[:space:]]*(#|$)' "$DOMAINS_FILE" || true
}

cmd_status() {
  [ -f "$STATE_FILE" ] || die "Not installed."
  # shellcheck disable=SC1090
  . "$STATE_FILE"
  say "Set this DNS on your Xbox: $PUBLIC_IP"
  say "Allowed home IP(s):        $HOME_IPS"
  say "dnsmasq (DNS):             $(systemctl is-active dnsmasq || true)"
  say "sniproxy (proxy):          $(systemctl is-active smartdns-sniproxy || true)"
  say "Domains routed:            $(cmd_list | wc -l)"
}

cmd_logs() {
  say "Domains asked in the last 30 minutes (count, domain):"
  journalctl -u dnsmasq --since "30 min ago" -o cat --no-pager 2>/dev/null \
    | awk '$1 ~ /^query\[(A|AAAA)\]$/ {print $2}' | sort | uniq -c | sort -rn | head -40 || true
}

cmd_uninstall() {
  need_root
  say "Removing Smart DNS (Amnezia is not touched)..."
  do_uninstall
  say "Done."
}

usage() {
  cat <<EOF
Usage:
  sudo bash smartdns.sh install [HOME_IP ...]
  sudo smartdns ip <IP> [more IPs] | none
  sudo smartdns add <domain>      /  sudo smartdns remove <domain>
  smartdns list | status | logs
  sudo smartdns uninstall
EOF
}

main() {
  case "${1:-}" in
    install)   shift; cmd_install "$@" ;;
    ip)        shift; cmd_ip "$@" ;;
    add)       shift; cmd_add "$@" ;;
    remove)    shift; cmd_remove "$@" ;;
    list)      cmd_list ;;
    status)    cmd_status ;;
    logs)      cmd_logs ;;
    uninstall) cmd_uninstall ;;
    *)         usage ;;
  esac
}

main "$@"
exit 0
