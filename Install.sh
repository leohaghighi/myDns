def parse_ip(s):
    try:
        ip = ipaddress.IPv4Address(s.strip())
    except ValueError:
        return None
    if not ip.is_global or str(ip) == SERVER_IP:
        return None
    return str(ip)


def all_ips():
    return sorted({e["ip"] for u in STATE["users"].values() for e in u["ips"]})


def cli(*args):
    r = subprocess.run([SMARTDNS, *args], capture_output=True, text=True, timeout=90)
    return ((r.stdout or "") + (r.stderr or "")).strip() or "(no output)", r.returncode


def apply_ips():
    out, code = cli("ip", *(all_ips() or ["none"]))
