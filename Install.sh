def poll():
    offset = 0
    while True:
        try:
            res = tg("getUpdates", offset=offset, timeout=50, allowed_updates=["message"])
            for upd in res.get("result", []):
                offset = upd["update_id"] + 1
                m = upd.get("message")
                if m:
                    try:
                        handle(m)
                    except Exception as e:  # noqa: BLE001
                        log("handler error:", repr(e))
        except urllib.error.HTTPError as e:
            if e.code == 401:
                log("Invalid bot token")
                sys.exit(1)
            log("poll http error:", e.code)
            time.sleep(5)
        except Exception as e:  # noqa: BLE001
            log("poll error:", repr(e))
            time.sleep(5)


