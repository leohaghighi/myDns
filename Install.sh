def limited(ip):
    now = time.time()
    if len(HITS) > 1000:
        HITS.clear()
    hits = [t for t in HITS.get(ip, []) if now - t < 60]
    hits.append(now)
    HITS[ip] = hits
    return len(hits) > 20


class Handler(BaseHTTPRequestHandler):
    server_version = "x"
    sys_version = ""
    timeout = 10

    def log_message(self, *a):  # never log URLs (they contain tokens)
        pass

    def _reply(self, code, body):
        b = body.encode()
        self.send_response(code)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(b)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Robots-Tag", "noindex")
        self.end_headers()
        self.wfile.write(b)

    def _uid(self):
        m = re.fullmatch(r"/u/([A-Za-z0-9_-]{20,64})", self.path.split("?")[0])
        if not m:
            return None
        with LOCK:
            for uid, u in STATE["users"].items():
                if eq(u["token"], m.group(1)):
                    return uid
        return None

    def do_GET(self):
        if limited(self.client_address[0]):
            return self._reply(429, "Too many requests")
        if self._uid() is None:
            return self._reply(404, "Not found")
        self._reply(200, PAGE.replace("__IP__", self.client_address[0]))

    def do_POST(self):
        ip = self.client_address[0]
        if limited(ip):
            return self._reply(429, "Too many requests")
        try:
            self.rfile.read(min(int(self.headers.get("Content-Length") or 0), 1024))
        except Exception:  # noqa: BLE001
            pass
        uid = self._uid()
        if uid is None:
            return self._reply(404, "Not found")
        clean = parse_ip(ip)
        if not clean:
            return self._reply(400, "IP نامعتبر")
        try:
            set_ip(uid, clean)
        except RuntimeError as e:
            log("apply failed:", e)
            return self._reply(500, "Error")
        self._reply(200, DONE.replace("__IP__", clean))
        send(int(uid), f"✅ IP جدید از طریق لینک ثبت شد: {clean}")


