def redeem(uid, name, code, cid):
    """Handle /start <code>. Returns True if the message was fully handled."""
    now = time.time()
    for c in [c for c, v in STATE["invites"].items() if v["expires"] < now]:
        del STATE["invites"][c]
    claim = STATE.get("owner_claim")
    if claim and eq(code, claim):
        STATE["owner_claim"] = None
        new_user(uid, name, "owner")
        save()
        send(cid, "✅ تو مالک ربات شدی.\n\n" + help_text(uid), keyboard(uid))
        return True
    for c, v in list(STATE["invites"].items()):
        if eq(code, c):
            if uid in STATE["users"]:
                send(cid, "تو قبلاً عضو هستی.", keyboard(uid))
                return True
            del STATE["invites"][c]
            new_user(uid, name, v["role"])
            save()
            send(cid, "✅ دسترسی‌ات فعال شد.\n\n" + help_text(uid), keyboard(uid))
            if v.get("by"):
                send(int(v["by"]), f"✅ {name} با دعوت تو وارد شد ({v['role']}).")
            return True
    return False


def target_id(arg):
    a = arg.split()[0] if arg.split() else ""
    return a if a in STATE["users"] else None


def handle(msg):
    chat = msg["chat"]
    if chat.get("type") != "private":
        return
    cid = chat["id"]
    frm = msg["from"]
    uid = str(frm["id"])
    name = (
        " ".join(x for x in [frm.get("first_name"), frm.get("last_name")] if x)
        or frm.get("username")
        or uid
    )
    text = (msg.get("text") or "").strip()
    text = BUTTONS.get(text, text)
    cmd, _, arg = text.partition(" ")
    cmd = cmd.split("@")[0].lower()
    arg = arg.strip()

    with LOCK:
        if cmd == "/start" and arg and redeem(uid, name, arg, cid):
            return
        if uid not in STATE["users"]:
            send(cid, "⛔ دسترسی نداری. از مدیر ربات لینک دعوت بگیر.")
            return
        me = STATE["users"][uid]
        admin = is_admin(uid)
        owner = role(uid) == "owner"

        # a bare IPv4 address = register it
        if cmd == "/ip" or re.fullmatch(r"\d{1,3}(\.\d{1,3}){3}", text):
            raw = arg if cmd == "/ip" else text
            ip = parse_ip(raw)
            if not ip:
                send(cid, "IP معتبر نیست (باید یک IPv4 عمومی باشد).")
                return
            try:
                set_ip(uid, ip)
            except RuntimeError as e:
                send(cid, f"❌ خطا در اعمال: {e}")
                return
            send(cid, f"✅ ثبت شد: {ip}\n(چند ثانیه بعد فعال است)")
            return

        if cmd in ("/start", "/help"):
            send(cid, help_text(uid), keyboard(uid))
        elif cmd == "/link":
            send(
                cid,
                "🔗 لینک شخصی تو:\n"
                f"http://{SERVER_IP}:{LINK_PORT}/u/{me['token']}\n\n"
                "با گوشی یا کامپیوتری که به اینترنت همان خانه‌ی ایکس‌باکس وصل است و VPN خاموش است "
